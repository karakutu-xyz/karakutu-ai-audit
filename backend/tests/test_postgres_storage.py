def test_postgres_engine_options_lock_and_connection_failure(monkeypatch):
    import audit.db as db
    calls = {}

    class Unreachable:
        def connect(self):
            raise OperationalError(None, None, Exception("fictional-private-password"))

        def dispose(self):
            calls["disposed"] = True

    def engine(url, **options):
        calls.update(options)
        return Unreachable()

    monkeypatch.setattr(db, "create_engine", engine)
    with pytest.raises(RuntimeError) as error:
        Store("postgresql+psycopg://audit:fictional-private-password@db.example.invalid/audit")
    assert str(error.value) == "Database unreachable (postgresql at db.example.invalid/audit)"
    assert error.value.__suppress_context__
    assert calls == {"pool_pre_ping": True, "pool_size": 5, "max_overflow": 5,
                     "pool_recycle": 1800, "connect_args": {"connect_timeout": 10},
                     "hide_parameters": True, "disposed": True}

    class Connection:
        class dialect:
            name = "postgresql"

        def exec_driver_sql(self, sql):
            calls["sql"] = sql

    begin_write(Connection())
    assert "pg_advisory_xact_lock" in calls["sql"]


def test_postgres_ddl_and_ordering_compile_offline():
    dialect = postgresql.dialect()
    for table in Base.metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=dialect))
        # Plain `json` keeps captured evidence verbatim, including \u0000; never `jsonb`.
        assert "JSONB" not in ddl
        if "seq" in table.c:
            assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
            assert "IDENTITY NULL" not in ddl
    index = next(index for index in ArticleRow.__table__.indexes if index.name == "uq_articles_archive_id")
    assert "WHERE archive_id IS NOT NULL" in str(CreateIndex(index).compile(dialect=dialect))
    for table in (PromptActivation, ModelAssignment, Run):
        query = select(table.id).order_by(insertion_order(table))
        assert ".rowid" in str(query.compile(dialect=sqlite.dialect()))
        expected = ".id" if table is Run else ".seq"
        assert str(query.compile(dialect=dialect)).endswith(expected)


def test_version_four_upgrade_retains_rows_and_runs_only_five(tmp_path):
    url = f"sqlite:///{tmp_path / 'version-four.sqlite3'}"
    store = Store(url)
    store.sync_prompt_defaults({"relevance": "Invented retained prompt"})
    store.assign_model("relevance", "invented-model", "Reviewer", "", lambda: {"id": "wf_test"})
    expected = store.active_prompts()
    store.close()
    # Reproduce old append-only tables without seq, keeping their rowids/order.
    with sqlite3.connect(tmp_path / "version-four.sqlite3") as connection:
        for table in ("prompt_activations", "model_assignments"):
            connection.execute(f"ALTER TABLE {table} DROP COLUMN seq")
        connection.execute("PRAGMA user_version=4")
    calls = []

    def migrate(connection):
        calls.append(5)
        MIGRATIONS[-1][1](connection)

    for _ in range(2):
        store = Store(url, migrations=[*MIGRATIONS[:-1], (5, migrate)])
        assert store.active_prompts() == expected
        assert store.model_assignments() == {"relevance": "invented-model"}
        for table in ("prompt_activations", "model_assignments"):
            assert "seq" in {col["name"] for col in inspect(store.engine).get_columns(table)}
        store.close()
    assert calls == [5]


def test_migration_five_failure_rolls_back(tmp_path):
    url = f"sqlite:///{tmp_path / 'rollback.sqlite3'}"
    store = Store(url)
    store.close()
    with sqlite3.connect(tmp_path / "rollback.sqlite3") as connection:
        for table in ("prompt_activations", "model_assignments"):
            connection.execute(f"ALTER TABLE {table} DROP COLUMN seq")
        connection.execute("PRAGMA user_version=4")

    def fail(connection):
        MIGRATIONS[-1][1](connection)
        raise RuntimeError("invented failure")

    with pytest.raises(RuntimeError, match="invented failure"):
        Store(url, migrations=[*MIGRATIONS[:-1], (5, fail)])
    with sqlite3.connect(tmp_path / "rollback.sqlite3") as connection:
        assert connection.execute("PRAGMA user_version").fetchone()[0] == 4
        for table in ("prompt_activations", "model_assignments"):
            assert "seq" not in {col[1] for col in connection.execute(f"PRAGMA table_info({table})")}


def test_portable_version_and_widths(database_url):
    store = Store(database_url)
    try:
        with store.engine.begin() as connection:
            begin_write(connection)
            assert get_version(connection) == SCHEMA_VERSION
            set_version(connection, SCHEMA_VERSION + 1)
        with pytest.raises(ValueError, match="newer"):
            Store(database_url)
        with store.engine.begin() as connection:
            begin_write(connection)
            set_version(connection, SCHEMA_VERSION)
        # Unbounded archive strings used to exceed VARCHAR limits on PostgreSQL.
        archive_id = "a" * 160
        source = "s" * 300
        store.import_articles([{"article_id": archive_id, "url": "https://archive.example/fictional",
                                "title": "Invented title", "newspaper": source,
                                "publish_date": "p" * 80}])
        detail = store.article("ka-" + archive_id)
        assert detail["source"] == source and len(detail["published_at"]) == 80
    finally:
        store.close()


def test_portable_failed_migration_rolls_back_ddl_data_and_stamp(database_url):
    from sqlalchemy import update
    from audit.db import Workflow

    store = Store(database_url)
    retained = {"id": "wf_retained", "definition": {"invented": True}}
    store.save_workflow(retained)
    store.close()

    def fail(connection):
        connection.exec_driver_sql("CREATE TABLE abandoned_migration (id INTEGER)")
        connection.execute(update(Workflow).values(snapshot={"invented": False}))
        raise RuntimeError("invented failure")

    with pytest.raises(RuntimeError, match="invented failure"):
        Store(database_url, migrations=[*MIGRATIONS, (SCHEMA_VERSION + 1, fail)])
    store = Store(database_url)
    try:
        assert store.workflow("wf_retained") == retained
        assert "abandoned_migration" not in inspect(store.engine).get_table_names()
        with store.engine.connect() as connection:
            assert get_version(connection) == SCHEMA_VERSION
    finally:
        store.close()


def test_store_reports_demo_data_on_any_backend(database_url):
    from audit.db import Store, Workflow
    from sqlalchemy.orm import Session
    store = Store(database_url)
    try:
        assert store.has_demo_data() is False
        with Session(store.engine) as session, session.begin():
            session.add(Workflow(id="wf_demoX", snapshot={"id": "wf_demoX"}))
        assert store.has_demo_data() is False
        with Session(store.engine) as session, session.begin():
            session.add(Workflow(id="wf_demo_v1", snapshot={"id": "wf_demo_v1"}))
        assert store.has_demo_data() is True
    finally:
        store.close()


def test_long_urls_are_stored_and_unique_on_any_backend(database_url):
    """A URL near the 4,096-character limit must not hit a B-tree entry-size limit."""
    import secrets
    from sqlalchemy.exc import IntegrityError
    from sqlalchemy.orm import Session
    from audit.db import ArticleRow, Store, article_values
    from test_db import workflow
    url = "https://paper.example/" + secrets.token_hex(2030)  # incompressible, about 4 KB
    store = Store(database_url)
    try:
        workflow(store)
        payload = {"removed_article": {"url": url, "title": "Fictional long URL",
                                       "content": "Fictional content."}}
        first = store.create_run(workflow_id="wf_test", category="benchmark",
                                 origin="benchmark", input=payload)
        second = store.create_run(workflow_id="wf_test", category="benchmark",
                                  origin="benchmark", input=payload)
        assert first["article_ref"] == second["article_ref"]
        assert store.articles()["total"] == 1
        with pytest.raises(IntegrityError), Session(store.engine) as session, session.begin():
            duplicate = article_values({"url": url, "title": "Duplicate", "content": "x"}, "live")
            duplicate["ref"] = "u-fictional-duplicate"
            session.add(ArticleRow(**duplicate))
    finally:
        store.close()


def test_workflow_evidence_with_nul_round_trips_exactly_on_any_backend(database_url):
    """Captured evidence (model output, search snippets, archive responses) may hold NUL.
    Run and workflow JSON columns store it verbatim on both backends; nothing is stripped."""
    from audit.db import Store
    from test_db import create, workflow
    store = Store(database_url)
    try:
        workflow(store)
        run = create(store)
        store.start_run(run["id"])
        step = {"name": "web_search", "evidence": [{"snippet": "fictional\x00 snippet",
                "raw\x00key": {"nested": ["a\x00b"], "number": 1.0e20}}],
                "model_calls": [{"reasoning": "x\x00y"}]}
        store.append_step(run["id"], step)
        result = {"response": {"verdict": "INCONCLUSIVE", "findings": "fictional\x00 finding"},
                  "steps": [step]}
        store.complete_run(run["id"], result)
        saved = store.run(run["id"])
        assert saved["status"] == "succeeded"
        assert saved["steps"] == [step]
        assert saved["output"]["findings"] == "fictional\x00 finding"
    finally:
        store.close()


def test_archive_removal_date_drops_nul_on_any_backend(database_url):
    from audit.clients.models import ArticleRecord
    from audit.db import Store
    store = Store(database_url)
    try:
        store.import_articles([{"article_id": 42, "url": "https://paper.example/archived"}])
        article = store.article("ka-42")
        record = ArticleRecord(id=42, url="https://paper.example/archived", versions=[
            {"title": "Fictional", "news_text": "Fictional text", "check_date": 1, "content_hash": "x"}],
            checks={"entries": [{"status": 404, "check_date": "2026-11-01\x00"}]})
        assert store.fill_article("ka-42", record, expected_url=article["url"],
                                  expected_archive_id=article["archive_id"]) is True
        filled = store.article("ka-42")
        assert filled["content"] == "Fictional text"
        assert filled["removed_at"] is None or "\x00" not in filled["removed_at"]
    finally:
        store.close()
